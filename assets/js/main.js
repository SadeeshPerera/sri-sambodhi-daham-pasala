function initAdmissionsWizard() {
  const wizardForm = document.getElementById('admissions-wizard-form');
  if (!wizardForm) return;

  const steps = wizardForm.querySelectorAll('.form-step');
  const nextBtns = wizardForm.querySelectorAll('.wizard-next-btn');
  const prevBtns = wizardForm.querySelectorAll('.wizard-prev-btn');
  const progressBar = document.getElementById('wizard-progress-bar');
  const stepIndicators = document.querySelectorAll('.wizard-step-indicator');
  const confirmationModal = document.getElementById('admission-confirmation-modal');

  let currentStep = 0;

  function showStep(index) {
    steps.forEach((step, idx) => {
      if (idx === index) {
        step.classList.remove('hidden');
      } else {
        step.classList.add('hidden');
      }
    });

    if (progressBar) {
      const pct = ((index + 1) / steps.length) * 100;
      progressBar.style.width = `${pct}%`;
    }

    stepIndicators.forEach((indicator, idx) => {
      if (idx <= index) {
        indicator.classList.add('bg-red-800', 'text-white', 'dark:bg-amber-500', 'dark:text-stone-950');
        indicator.classList.remove('bg-stone-200', 'text-stone-600', 'dark:bg-stone-800', 'dark:text-stone-400');
      } else {
        indicator.classList.remove('bg-red-800', 'text-white', 'dark:bg-amber-500', 'dark:text-stone-950');
        indicator.classList.add('bg-stone-200', 'text-stone-600', 'dark:bg-stone-800', 'dark:text-stone-400');
      }
    });
  }

  nextBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      // Basic check for required inputs on current step
      const currentInputs = steps[currentStep].querySelectorAll('input[required], select[required]');
      let allValid = true;
      currentInputs.forEach(input => {
        if (!input.value.trim()) {
          input.classList.add('border-red-500');
          allValid = false;
        } else {
          input.classList.remove('border-red-500');
        }
      });

      if (!allValid) {
        showToastNotification('කරුණාකර අනිවාර්ය තොරතුරු නිවැරදිව පුරවන්න.', 'error');
        return;
      }

      if (currentStep < steps.length - 1) {
        currentStep++;
        showStep(currentStep);
        window.scrollTo({ top: wizardForm.offsetTop - 120, behavior: 'smooth' });
      }
    });
  });

  prevBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      if (currentStep > 0) {
        currentStep--;
        showStep(currentStep);
      }
    });
  });

  wizardForm.addEventListener('submit', (e) => {
    e.preventDefault();
    const studentName = document.getElementById('adm-student-name')?.value || 'ශිෂ්‍ය නාමය';
    const grade = document.getElementById('adm-grade')?.value || '1 ශ්‍රේණිය';
    const refCode = 'SSDP-2027-' + Math.floor(1000 + Math.random() * 9000);

    const receiptName = document.getElementById('receipt-student-name');
    const receiptGrade = document.getElementById('receipt-grade');
    const receiptCode = document.getElementById('receipt-code');

    if (receiptName) receiptName.innerText = studentName;
    if (receiptGrade) receiptGrade.innerText = grade;
    if (receiptCode) receiptCode.innerText = refCode;

    if (confirmationModal) {
      confirmationModal.classList.add('active');
    }
  });

  showStep(0);
}

