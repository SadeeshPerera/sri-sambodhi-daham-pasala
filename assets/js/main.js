function showToastNotification(message, type = 'info') {
  let toastContainer = document.getElementById('toast-container');
  if (!toastContainer) {
    toastContainer = document.createElement('div');
    toastContainer.id = 'toast-container';
    toastContainer.className = 'fixed bottom-5 right-5 z-50 flex flex-col gap-2 max-w-sm w-full pointer-events-none';
    document.body.appendChild(toastContainer);
  }

  const toast = document.createElement('div');
  const bg = type === 'success' ? 'bg-emerald-800 text-white' : type === 'error' ? 'bg-red-800 text-white' : 'bg-stone-900 text-white';
  const icon = type === 'success' ? 'fa-circle-check' : type === 'error' ? 'fa-triangle-exclamation' : 'fa-circle-info';

  toast.className = `${bg} shadow-2xl rounded-xl p-3.5 flex items-center gap-3 text-sm font-medium transition-all duration-300 pointer-events-auto transform translate-y-4 opacity-0 border border-white/10`;
  const iconEl = document.createElement('i');
  iconEl.className = `fa-solid ${icon} text-amber-300 text-base`;
  const textSpan = document.createElement('span');
  textSpan.className = 'flex-1';
  textSpan.textContent = message; // Safe client-side output sanitization
  toast.appendChild(iconEl);
  toast.appendChild(textSpan);

  toastContainer.appendChild(toast);

  setTimeout(() => {
    toast.classList.remove('translate-y-4', 'opacity-0');
  }, 10);

  setTimeout(() => {
    toast.classList.add('translate-y-4', 'opacity-0');
    setTimeout(() => toast.remove(), 300);
  }, 4000);
}

/* -------------------------------------------------------------
 * 16. CLIENT-SIDE XSS SANITIZER & SECURITY HARDENING
 * ------------------------------------------------------------- */
function sanitizeInput(str) {
  if (typeof str !== 'string') return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
    .trim();
}

function initSecurityAndSanitization() {
  // 1. Enforce rel="noopener noreferrer" on all external & new-tab links
  document.querySelectorAll('a[target="_blank"], a[href^="http://"], a[href^="https://"]').forEach(a => {
    const rel = (a.getAttribute('rel') || '').split(/\s+/).filter(Boolean);
    if (!rel.includes('noopener')) rel.push('noopener');
    if (!rel.includes('noreferrer')) rel.push('noreferrer');
    a.setAttribute('rel', rel.join(' '));
  });

  // 2. Sanitize and handle contact form submission
  const contactForm = document.getElementById('contact-inquiry-form');
  if (contactForm) {
    contactForm.addEventListener('submit', (e) => {
      e.preventDefault();
      const nameInput = contactForm.querySelector('input[type="text"]');
      const phoneInput = contactForm.querySelector('input[type="tel"]');
      const emailInput = contactForm.querySelector('input[type="email"]');
      const msgTextarea = contactForm.querySelector('textarea');

      const cleanName = sanitizeInput(nameInput ? nameInput.value : '');
      const cleanPhone = sanitizeInput(phoneInput ? phoneInput.value : '');
      const cleanEmail = sanitizeInput(emailInput ? emailInput.value : '');
      const cleanMsg = sanitizeInput(msgTextarea ? msgTextarea.value : '');

      if (!cleanName || !cleanPhone || !cleanMsg) {
        showToastNotification('කරුණාකර සියලු අනිවාර්ය තොරතුරු නිවැරදිව පුරවන්න.', 'error');
        return;
      }

      const currentLang = localStorage.getItem('sambodhi_lang') || 'si';
      const successMsg = currentLang === 'en'
        ? `Thank you, ${cleanName}! Your inquiry has been submitted securely.`
        : `ස්තූතියි ${cleanName}! ඔබගේ පණිවිඩය සාර්ථකව හා ආරක්ෂිතව යොමු විය.`;

      showToastNotification(successMsg, 'success');
      contactForm.reset();
    });
  }
}

/* -------------------------------------------------------------
 * 17. CLEAN URL NAVIGATION & PROTOCOL ROUTING
 * ------------------------------------------------------------- */
function initCleanUrlNavigation() {
  const rawPath = window.location.pathname.replace(/\/$/, '').split('/').pop() || 'index';
  const cleanRouteKey = rawPath.replace(/\.html$/, '') || 'index';
  const currentRoute = (cleanRouteKey === 'index' || cleanRouteKey === '') ? '/' : '/' + cleanRouteKey;

  // Active desktop header link
  document.querySelectorAll('#main-header nav a').forEach(link => {
    const href = link.getAttribute('href');
    if (href === currentRoute || (currentRoute === '/' && href === '/')) {
      link.classList.add('text-red-900', 'dark:text-amber-400', 'font-bold');
    }
  });

  // Active mobile drawer link
  document.querySelectorAll('#mobile-drawer nav a').forEach(link => {
    const href = link.getAttribute('href');
    const isCurrent = href === currentRoute || (currentRoute === '/' && href === '/');
    if (isCurrent) {
      link.className = 'p-2.5 rounded-lg bg-red-100 dark:bg-red-950/40 text-red-900 dark:text-amber-300 font-bold';
    } else {
      link.className = 'p-2.5 rounded-lg hover:bg-stone-100 dark:hover:bg-stone-900 text-stone-800 dark:text-stone-200';
    }
  });

  // Safe file:// protocol fallback so local file browsing works seamlessly
  if (window.location.protocol === 'file:') {
    document.addEventListener('click', (e) => {
      const anchor = e.target.closest('a');
      if (!anchor) return;
      const href = anchor.getAttribute('href');
      if (href && href.startsWith('/') && !href.startsWith('//')) {
        e.preventDefault();
        const hashIdx = href.indexOf('#');
        const hash = hashIdx !== -1 ? href.substring(hashIdx) : '';
        const pathOnly = hashIdx !== -1 ? href.substring(0, hashIdx) : href;
        const targetFile = (pathOnly === '/' || pathOnly === '') ? 'index.html' : pathOnly.substring(1) + '.html';
        window.location.href = targetFile + hash;
      }
    });
  }
}
