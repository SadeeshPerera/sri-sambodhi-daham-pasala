function initDhammapadaGenerator() {
  const paliEl = document.getElementById('dhamma-pali');
  const sinhalaEl = document.getElementById('dhamma-sinhala');
  const englishEl = document.getElementById('dhamma-english');
  const sourceEl = document.getElementById('dhamma-source');
  const nextBtn = document.getElementById('next-dhamma-btn');

  if (!paliEl || !sinhalaEl || !nextBtn) return;

  let currentIndex = 0; // Default to school motto stanza: Sabba Danam Dhamma Danam Jinati

  function displayVerse(idx) {
    const item = DHAMMAPADA_VERSES[idx];
    if (!item) return;
    paliEl.innerText = (item.pali || '').replace(/\\n/g, '\n');
    sinhalaEl.innerText = (item.sinhala || '').replace(/\\n/g, '\n');
    if (englishEl) englishEl.innerText = (item.english || '').replace(/\\n/g, '\n');
    if (sourceEl) {
      sourceEl.setAttribute('data-lang-si', item.source || '');
      sourceEl.setAttribute('data-lang-en', item.source_en || item.source || '');
      const curLang = localStorage.getItem('sambodhi_lang') || 'si';
      sourceEl.innerText = (curLang === 'en' && item.source_en) ? item.source_en : item.source;
    }
  }

  nextBtn.addEventListener('click', (e) => {
    e.preventDefault();
    currentIndex = (currentIndex + 1) % DHAMMAPADA_VERSES.length;
    paliEl.style.opacity = 0;
    sinhalaEl.style.opacity = 0;
    setTimeout(() => {
      displayVerse(currentIndex);
      paliEl.style.opacity = 1;
      sinhalaEl.style.opacity = 1;
    }, 200);
  });

  window.updateDhammapadaSourceLang = function(lang) {
    const item = DHAMMAPADA_VERSES[currentIndex];
    if (sourceEl && item) {
      sourceEl.setAttribute('data-lang-si', item.source || '');
      sourceEl.setAttribute('data-lang-en', item.source_en || item.source || '');
      sourceEl.innerText = (lang === 'en' && item.source_en) ? item.source_en : item.source;
    }
  };

  displayVerse(currentIndex);
}

