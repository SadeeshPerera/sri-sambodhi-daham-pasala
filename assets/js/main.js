/* -------------------------------------------------------------
 * 7. 50TH GOLDEN JUBILEE COUNTDOWN (1977 - 2027)
 * ------------------------------------------------------------- */
function initJubileeCountdown() {
  const countdownCards = document.querySelectorAll('#jubilee-countdown-card, .jubilee-countdown-card, #jubilee-countdown');
  const daysEls = document.querySelectorAll('#cd-days, .cd-days');
  const hoursEls = document.querySelectorAll('#cd-hours, .cd-hours');
  const minutesEls = document.querySelectorAll('#cd-mins, .cd-mins');
  const secondsEls = document.querySelectorAll('#cd-secs, .cd-secs');

  if (daysEls.length === 0 && countdownCards.length === 0) return;

  // Target: January 1, 2027
  const targetDate = new Date('2027-01-01T00:00:00+05:30').getTime();

  function update() {
    const now = new Date().getTime();
    const distance = targetDate - now;

    // Auto-hide if distance is zero or days run out
    if (distance <= 0) {
      countdownCards.forEach(card => {
        card.style.display = 'none';
      });
      return;
    }

    const days = Math.floor(distance / (1000 * 60 * 60 * 24));
    const hours = Math.floor((distance % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
    const minutes = Math.floor((distance % (1000 * 60 * 60)) / (1000 * 60));
    const seconds = Math.floor((distance % (1000 * 60)) / 1000);

    if (days <= 0 && distance <= 0) {
      countdownCards.forEach(card => {
        card.style.display = 'none';
      });
      return;
    }

    daysEls.forEach(el => el.textContent = String(days).padStart(2, '0'));
    hoursEls.forEach(el => el.textContent = String(hours).padStart(2, '0'));
    minutesEls.forEach(el => el.textContent = String(minutes).padStart(2, '0'));
    secondsEls.forEach(el => el.textContent = String(seconds).padStart(2, '0'));
  }

  update();
  setInterval(update, 1000);
}

