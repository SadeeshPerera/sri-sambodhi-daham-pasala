function initMobileDrawer() {
  const toggleBtn = document.getElementById('mobile-drawer-toggle');
  const drawer = document.getElementById('mobile-drawer');
  const closeBtn = document.getElementById('mobile-drawer-close');
  const backdrop = document.getElementById('mobile-drawer-backdrop');

  if (!toggleBtn || !drawer) return;

  function openDrawer() {
    drawer.classList.remove('translate-x-full');
    if (backdrop) backdrop.classList.remove('hidden', 'opacity-0');
    document.body.classList.add('overflow-hidden');
  }

  function closeDrawer() {
    drawer.classList.add('translate-x-full');
    if (backdrop) backdrop.classList.add('opacity-0');
    setTimeout(() => {
      if (backdrop) backdrop.classList.add('hidden');
    }, 300);
    document.body.classList.remove('overflow-hidden');
  }

  toggleBtn.addEventListener('click', openDrawer);
  if (closeBtn) closeBtn.addEventListener('click', closeDrawer);
  if (backdrop) backdrop.addEventListener('click', closeDrawer);

  // Accordion within mobile nav
  const subToggles = drawer.querySelectorAll('.mobile-submenu-toggle');
  subToggles.forEach(btn => {
    btn.addEventListener('click', () => {
      const target = btn.nextElementSibling;
      const icon = btn.querySelector('.mobile-submenu-arrow');
      if (target) {
        target.classList.toggle('hidden');
        if (icon) icon.classList.toggle('rotate-180');
      }
    });
  });
}

